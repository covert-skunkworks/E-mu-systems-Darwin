//  Description:
//
//		bin2c.c -- turn a file into a C array, so the program carries it built in.
//
//		  usage: bin2c IN OUT NAME
//
//		writes OUT with
//
//		  const unsigned char NAME[] = { ..., 0 };   // the bytes, then a 0
//		  const unsigned long NAME_len = n;          // the file's size
//

//------------------------------------------------------------------------------
//------------------------------- Includes -------------------------------------
//------------------------------------------------------------------------------

#include <stdio.h>

//------------------------------------------------------------------------------
//------------------------------ Public API ------------------------------------
//------------------------------------------------------------------------------

/**
  * @brief  Write the array.
  *
  * @param  argc Argument count.
  * @param  argv IN OUT NAME.
  *
  * @retval 0 written, 1 failed.
  */
int main( int argc, char **argv )
{
	FILE *in, *out;
	unsigned long n = 0;
	int c;

	if ( argc != 4 )
	{
		fprintf( stderr, "usage: bin2c IN OUT NAME\n" );
		return 1;
	}
	in = fopen( argv[1], "rb" );
	if ( !in )
	{
		fprintf( stderr, "bin2c: cannot read %s\n", argv[1] );
		return 1;
	}
	out = fopen( argv[2], "w" );
	if ( !out )
	{
		fclose( in );
		fprintf( stderr, "bin2c: cannot write %s\n", argv[2] );
		return 1;
	}
	fprintf( out, "// %s, generated by tools/bin2c.c: do not edit\n", argv[1] );
	fprintf( out, "const unsigned char %s[] = {\n", argv[3] );
	while ( ( c = fgetc( in ) ) != EOF )
	{
		fprintf( out, "%d,%s", c, ++n % 24 ? "" : "\n" );
	}
	fprintf( out, "0\n};\nconst unsigned long %s_len = %luUL;\n", argv[3], n );
	fclose( in );
	return fclose( out ) == 0 ? 0 : 1;
}
